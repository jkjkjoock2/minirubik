#!/usr/bin/env python3
"""gen_render.py - generate the LED renderer's data tables as ida/render.s.

The layout follows the design in the HackMD note (Stage 4, LED matrix):
  * report.md's exterior net: UP above FRONT, then LEFT FRONT RIGHT BACK,
    DOWN below FRONT; 8 x 6 facelets of 4 x 3 pixels, one-pixel separators
    between face columns and face rows: 35 x 20 pixels on the 35 x 25 matrix.
  * Sticker model: position i's sticker k shows sticker (k + o[i]) mod 3 of
    cubie p[i] (checked against a real cube by /tmp/check_facelets.py).
  * Arrays of 8 entries, position 0 being the fixed corner (cubie 0, twist 0).

Usage:  python3 ida/gen_render.py                 write ida/render.s
        python3 ida/gen_render.py --preview "R B'" print the net as letters
"""
import sys

WIDTH = 35

# solver.c: source[face][dest] and twist[face][dest] over positions 1..7
SRC = [[1, 4, 2, 0, 3, 5, 6], [0, 1, 2, 4, 5, 6, 3], [0, 2, 5, 3, 1, 4, 6]]
TWIST = [[1, 2, 0, 2, 1, 0, 0], [0, 0, 0, 1, 2, 1, 2], [0] * 7]

# Stickers of each position: U/D first, then clockwise seen from outside.
FACES = {0: "UFL", 1: "URF", 2: "DFR", 3: "DLF",
         4: "UBR", 5: "DRB", 6: "DBL", 7: "ULB"}

RGB = {"U": 0xFFFFFF, "D": 0xFFFF00, "F": 0x00C000,
       "B": 0x0000FF, "R": 0xFF0000, "L": 0xFF8000}

# report.md's net: face -> (first column, first row, 2 x 2 positions)
NET = {"U": (2, 0, [[7, 4], [0, 1]]),
       "L": (0, 2, [[7, 0], [6, 3]]),
       "F": (2, 2, [[0, 1], [3, 2]]),
       "R": (4, 2, [[1, 4], [2, 5]]),
       "B": (6, 2, [[4, 7], [5, 6]]),
       "D": (2, 4, [[3, 2], [6, 5]])}


def facelets():
    """(byte offset, position, k, column, row) for the 24 facelets."""
    out = []
    for face, (col0, row0, grid) in NET.items():
        for dr in range(2):
            for dc in range(2):
                col, row = col0 + dc, row0 + dr
                pos = grid[dr][dc]
                x = 4 * col + col // 2
                y = 3 * row + row // 2
                out.append(((y * WIDTH + x) * 4, pos, FACES[pos].index(face),
                            col, row))
    return out


def source8():
    return [[0] + [s + 1 for s in SRC[f]] for f in range(3)]


def twist8():
    return [[0] + TWIST[f] for f in range(3)]


def check(fl):
    assert len(fl) == 24
    assert len({f[0] for f in fl}) == 24, "two facelets share a pixel"
    for pos in range(8):
        ks = sorted(f[2] for f in fl if f[1] == pos)
        assert ks == [0, 1, 2], f"position {pos} stickers {ks}"
    last = max(f[0] for f in fl) + 292            # bottom-right pixel
    assert last < WIDTH * 25 * 4


def preview(moves):
    p8, o8 = list(range(8)), [0] * 8
    s8, t8 = source8(), twist8()
    for m in moves.split():
        f = "RBD".index(m[0])
        for _ in range({"": 1, "2": 2, "'": 3}[m[1:]]):
            p8, o8 = ([p8[s8[f][i]] for i in range(8)],
                      [(o8[s8[f][i]] + t8[f][i]) % 3 for i in range(8)])
    grid = [[" "] * 8 for _ in range(6)]
    for _, pos, k, col, row in facelets():
        grid[row][col] = FACES[p8[pos]][(k + o8[pos]) % 3]
    for row in grid:
        print(" ".join(row[0:2]), " ", " ".join(row[2:4]), " ",
              " ".join(row[4:6]), " ", " ".join(row[6:8]))


def emit(path):
    fl = facelets()
    check(fl)
    lines = ["# Generated by ida/gen_render.py. Do not edit.",
             "# Data for the LED renderer (GUI build only).",
             ".data", ".align 2"]
    lines.append("cubie_rgb:      # [8][4]: RGB of cubie c's sticker j at 16c + 4j")
    for c in range(8):
        cols = [RGB[ch] for ch in FACES[c]] + [0]
        lines.append(".word " + ", ".join(f"0x{v:06X}" for v in cols))
    lines.append("facelet_offset: # [24]: byte offset of each facelet's top-left pixel")
    lines.append(".word " + ", ".join(str(f[0]) for f in fl))
    lines.append("facelet_pos:    # [24]: position 0..7 of each facelet")
    lines.append(".byte " + ", ".join(str(f[1]) for f in fl))
    lines.append("facelet_k:      # [24]: which sticker (0..2) of that position")
    lines.append(".byte " + ", ".join(str(f[2]) for f in fl))
    lines.append("source8:        # [3][8]: new[i] = old[source8[f][i]]")
    for row in source8():
        lines.append(".byte " + ", ".join(map(str, row)))
    lines.append("twist8:         # [3][8]: twist added at position i")
    for row in twist8():
        lines.append(".byte " + ", ".join(map(str, row)))
    lines.append("p8:  .zero 8    # cubie at each position (0 = fixed corner)")
    lines.append("o8:  .zero 8    # twist at each position")
    lines.append("p8b: .zero 8    # second buffer for a quarter turn")
    lines.append("o8b: .zero 8")
    with open(path, "w") as out:
        out.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--preview":
        preview(sys.argv[2])
    else:
        emit("ida/render.s")
        print("wrote ida/render.s")
